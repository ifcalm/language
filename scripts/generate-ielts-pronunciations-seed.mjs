// One-off: writes migrations/0243_seed_ielts_pronunciations.sql from the
// generated static data (IPA from scripts/fixtures/ielts-phonetics*.json).
// Row ids: {word_id}-{accent}, or {word_id}-{pos}-{accent} for words whose
// reading depends on part of speech (increase-n-uk); the same keys name the
// audio files (ielts/pronunciations/v1/{accent}/{word_id}[-{pos}].m4a).
// After this seed, D1 is the source of truth for ielts_pronunciations.
import { readFileSync, writeFileSync } from 'node:fs'

const OUTPUT_PATH = 'migrations/0243_seed_ielts_pronunciations.sql'
const MODULES = ['listening', 'reading', 'writing', 'speaking']
const ROWS_PER_INSERT = 300

function sqlString(value) {
  return value === null ? 'NULL' : `'${value.replaceAll("'", "''")}'`
}

const entries = MODULES.flatMap(
  (module) => JSON.parse(readFileSync(`src/data/ielts/generated/${module}.json`, 'utf8')).entries,
)
const rows = []

for (const entry of entries) {
  for (const accent of ['uk', 'us']) {
    if (entry.posPhonetics) {
      for (const row of entry.posPhonetics) {
        rows.push({
          id: `${entry.id}-${row.pos.replace(/\./g, '')}-${accent}`,
          wordId: entry.id,
          accent,
          pos: row.pos,
          phonetic: row[accent],
        })
      }
    } else {
      // Pattern phrases have no IPA but still get audio, so they keep a row.
      const phonetic = (accent === 'uk' ? entry.phoneticUk : entry.phoneticUs) ?? ''
      rows.push({ id: `${entry.id}-${accent}`, wordId: entry.id, accent, pos: null, phonetic })
    }
  }
}

const ids = new Set(rows.map((row) => row.id))

if (ids.size !== rows.length) {
  throw new Error('Duplicate pronunciation ids')
}

const statements = []

for (let index = 0; index < rows.length; index += ROWS_PER_INSERT) {
  const values = rows
    .slice(index, index + ROWS_PER_INSERT)
    .map((row) => `(${[row.id, row.wordId, row.accent, row.pos, row.phonetic].map(sqlString).join(', ')})`)
    .join(',\n')

  statements.push(
    `INSERT INTO ielts_pronunciations (id, word_id, accent, pos, phonetic) VALUES\n${values};`,
  )
}

writeFileSync(
  OUTPUT_PATH,
  `-- Seed ${rows.length} IELTS pronunciations (generated by scripts/generate-ielts-pronunciations-seed.mjs).\n${statements.join('\n\n')}\n`,
)
console.log(`Wrote ${rows.length} rows -> ${OUTPUT_PATH}`)
