// One-off: writes migrations/0241_seed_ielts_words.sql from
// docs/ielts-vocabulary.md so the existing 4557 entries enter D1 with the ids
// the static data already uses. After this seed, D1 is the source of truth
// for ielts_words; do not re-run it against a populated table.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { normalizeWord, readIeltsSource } from './lib/ielts-vocabulary-source.mjs'

const OUTPUT_PATH = 'migrations/0241_seed_ielts_words.sql'
const US_DICTIONARY_PATH = '.runtime/ipa-dict/en_US.txt'
const ROWS_PER_INSERT = 200

// British -> American spellings the suffix rules below cannot derive.
const US_SPELLING_EXCEPTIONS = {
  aluminium: 'aluminum',
  mould: 'mold',
  tyre: 'tire',
  programme: 'program',
  grey: 'gray',
  jewellery: 'jewelry',
  sceptical: 'skeptical',
  mollusc: 'mollusk',
  plough: 'plow',
  storey: 'story',
  catalogue: 'catalog',
  enrol: 'enroll',
  enrolment: 'enrollment',
  instil: 'instill',
  wilful: 'willful',
  fulfil: 'fulfill',
  instalment: 'installment',
  cheque: 'check',
  ageing: 'aging',
  licence: 'license',
  defence: 'defense',
  offence: 'offense',
  cosy: 'cozy',
  artefact: 'artifact',
  manoeuvre: 'maneuver',
  anaesthetic: 'anesthetic',
  foetal: 'fetal',
  sulphur: 'sulfur',
  pedestrianise: 'pedestrianize',
  // British forms that also appear in the US dictionary.
  behaviour: 'behavior',
  behavioural: 'behavioral',
  labour: 'labor',
  favour: 'favor',
  harbour: 'harbor',
  rumour: 'rumor',
  armour: 'armor',
  odour: 'odor',
  endeavour: 'endeavor',
  neighbour: 'neighbor',
  neighbourhood: 'neighborhood',
  neighbouring: 'neighboring',
  centre: 'center',
  fibre: 'fiber',
  traveller: 'traveler',
  recognise: 'recognize',
  organisation: 'organization',
}

const SUFFIX_RULES = [
  [/is(e|ed|es|ing|ation|ations|er|ers)$/, 'iz$1'],
  [/ys(e|ed|es|ing)$/, 'yz$1'],
  [/our(s|ed|ing|ful|less|ite|able)?$/, 'or$1'],
  [/(ce|ti|bi|fi|li|me|nt|b)re$/, '$1er'],
  [/ogue$/, 'og'],
  [/ll(ed|ing|er|ers)$/, 'l$1'],
  [/ae/, 'e'],
  [/oe/, 'e'],
]

if (!existsSync(US_DICTIONARY_PATH)) {
  throw new Error(`Missing ${US_DICTIONARY_PATH}; run npm run ielts:phonetics first.`)
}

const usWords = new Set(
  readFileSync(US_DICTIONARY_PATH, 'utf8')
    .split('\n')
    .map((line) => line.split('\t')[0]?.toLowerCase())
    .filter(Boolean),
)

// A British form gets an American spelling only when the American form is a
// known US word and the British form is not (so "advertise" stays as is).
function toUsToken(token) {
  if (US_SPELLING_EXCEPTIONS[token]) {
    return US_SPELLING_EXCEPTIONS[token]
  }

  if (usWords.has(token)) {
    return token
  }

  for (const [pattern, replacement] of SUFFIX_RULES) {
    const candidate = token.replace(pattern, replacement)

    if (candidate !== token && usWords.has(candidate)) {
      return candidate
    }
  }

  return token
}

function toUsSpelling(word) {
  const lower = normalizeWord(word)
  const us = lower.replace(/[a-z]+/g, (token) => toUsToken(token))
  return us === lower ? null : us
}

function sqlString(value) {
  return value === null ? 'NULL' : `'${value.replaceAll("'", "''")}'`
}

const rows = readIeltsSource()
  .flatMap((module) => module.topics)
  .flatMap((topic) => topic.entries)
  .map((entry) => ({
    id: entry.id,
    word: entry.word,
    normalizedWord: normalizeWord(entry.word),
    spellingUs: toUsSpelling(entry.word),
    meaningZh: entry.senses.map((sense) => `${sense.pos} ${sense.meaning}`).join(' '),
  }))

const ids = new Set()

for (const row of rows) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(row.id)) {
    throw new Error(`Invalid id "${row.id}" for "${row.word}"`)
  }

  if (ids.has(row.id)) {
    throw new Error(`Duplicate id "${row.id}"`)
  }

  ids.add(row.id)
}

const statements = []

for (let index = 0; index < rows.length; index += ROWS_PER_INSERT) {
  const values = rows
    .slice(index, index + ROWS_PER_INSERT)
    .map((row) =>
      `(${[row.id, row.word, row.normalizedWord, row.spellingUs, row.meaningZh].map(sqlString).join(', ')})`,
    )
    .join(',\n')

  statements.push(
    `INSERT INTO ielts_words (id, word, normalized_word, spelling_us, meaning_zh) VALUES\n${values};`,
  )
}

writeFileSync(
  OUTPUT_PATH,
  `-- Seed ${rows.length} IELTS entries from docs/ielts-vocabulary.md (generated by scripts/generate-ielts-words-seed.mjs).\n${statements.join('\n\n')}\n`,
)

const withUs = rows.filter((row) => row.spellingUs)
console.log(`Wrote ${rows.length} rows (${withUs.length} with spelling_us) -> ${OUTPUT_PATH}`)

if (process.argv.includes('--list-us')) {
  console.log(withUs.map((row) => `${row.word} -> ${row.spellingUs}`).join('\n'))
}
